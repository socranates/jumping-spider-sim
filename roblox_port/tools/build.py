"""Stamp evidence and build the playable and Studio-test places. No publishing.
Usage: python tools/build.py path/to/rojo
"""
from pathlib import Path
import hashlib,json,subprocess,sys
root=Path(__file__).resolve().parents[1]
paths=sorted([*root.glob('src/**/*.luau'),*root.glob('tests/**/*.luau'),*root.glob('*.project.json')])
h=hashlib.sha256()
for p in paths:
    if p.name=='BuildInfo.luau':continue
    h.update(p.relative_to(root).as_posix().encode()+b'\0'+p.read_bytes()+b'\0')
evidence=h.hexdigest()[:16]
(root/'tests/studio/BuildInfo.luau').write_text(f'-- Generated by tools/build.py; do not edit.\nreturn {{ id = "{evidence}" }}\n',encoding='utf-8')
rojo=sys.argv[1] if len(sys.argv)>1 else 'rojo'
for project,output in [('default.project.json','TheWindowsill.rbxlx'),('tests.project.json','TheWindowsillTests.rbxlx')]:
    subprocess.run([rojo,'build',str(root/project),'-o',str(root/output)],check=True)
print('evidence_id:',evidence)
