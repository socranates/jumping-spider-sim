#!/usr/bin/env python3
"""Regenerates src/Shared/Data/*.luau from the Godot game's data/species and data/surfaces JSON, so the numbers stay identical.
Run from roblox_port/:  python3 tools/json_to_luau.py"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "Shared" / "Data"


def lua(v, ind=1):
    pad = "\t" * ind
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "nil"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x, ind) for x in v) + " }"
    items = [f"{pad}{k} = {lua(x, ind + 1)}," for k, x in v.items() if x is not None]
    return "{\n" + "\n".join(items) + "\n" + "\t" * (ind - 1) + "}"


def emit(folder, name, doc):
    table = {}
    for f in sorted((ROOT / "data" / folder).glob("*.json")):
        d = json.loads(f.read_text())
        table[d["id"]] = d
    src = f"--!strict\n-- GENERATED by tools/json_to_luau.py from data/{folder}/*.json. Do not edit by hand.\n-- {doc}\n"
    src += "local data = " + lua(table) + "\n\nreturn table.freeze(data)\n"
    (OUT / f"{name}.luau").write_text(src)
    print("wrote", name, len(table))


emit("species", "Species", "Species profiles. 1 Godot WU = 1 stud, so every value is unchanged.")
emit("surfaces", "Surfaces", "Surface profiles, looked up by a part's ProfileId attribute.")
